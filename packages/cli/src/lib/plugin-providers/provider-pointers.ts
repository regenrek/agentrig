async function collectSkillSummaries(pluginDir: string, plugin: PluginEntry): Promise<SkillSummary[]> {
  const skillsRoot = path.join(pluginDir, 'skills')
  const summaries: SkillSummary[] = []
  try {
    const entries = await fs.readdir(skillsRoot, { withFileTypes: true })
    for (const entry of entries) {
      if (!entry.isDirectory()) continue
      const skillPath = path.join(skillsRoot, entry.name, 'SKILL.md')
      const text = await fs.readFile(skillPath, 'utf-8').catch(() => '')
      const frontmatter = parseFrontmatter(text)
      summaries.push({
        id: entry.name,
        name: frontmatter.name ?? entry.name,
        ...(frontmatter.description ? { description: shorten(frontmatter.description, 150) } : {}),
      })
    }
  } catch {
    // Skills are optional for provider bundles.
  }

  const declared = declaredSkillIds(summaries, plugin)
  return declared.sort((left, right) => left.id.localeCompare(right.id))
}

function declaredSkillIds(existing: SkillSummary[], plugin: PluginEntry) {
  return [...new Map(existing.map((entry) => [entry.id, entry])).values()]
}

function parseFrontmatter(text: string): { name?: string; description?: string } {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  if (!match) return {}
  const values: { name?: string; description?: string } = {}
  for (const line of match[1]!.split(/\r?\n/)) {
    const field = line.match(/^(name|description):\s*(.*)$/)
    if (!field) continue
    const value = field[2]!.trim().replace(/^['"]|['"]$/g, '')
    if (field[1] === 'name') values.name = value
    if (field[1] === 'description') values.description = value
  }
  return values
}

function formatSkillBullets(skills: SkillSummary[]) {
  if (!skills.length) return ['- No skills directory was exported for this plugin.']
  const visible = skills.slice(0, MAX_LISTED_SKILLS)
  const lines = visible.map((skill) => {
    const description = skill.description ?? skill.name
    return `- \`${skill.id}\`: ${description}`
  })
  if (skills.length > visible.length) {
    lines.push(`- ${skills.length - visible.length} more skills are available in \`skills/\`.`)
  }
  return lines
}

function shorten(value: string, maxLength: number) {
  const normalized = value.replace(/\s+/g, ' ').trim()
  if (normalized.length <= maxLength) return normalized
  return `${normalized.slice(0, maxLength - 1).trimEnd()}...`
}
