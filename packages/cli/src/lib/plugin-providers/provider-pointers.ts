import { promises as fs } from 'node:fs'
import path from 'node:path'
import type { PluginEntry, PluginFeatures } from './shared'
import { pluginDisplayName } from './shared'

type SkillSummary = {
  id: string
  name: string
  description?: string
}

const MAX_LISTED_SKILLS = 25

export async function writeCodexProviderPointer(pluginDir: string, plugin: PluginEntry, features: PluginFeatures) {
  await fs.mkdir(pluginDir, { recursive: true })
  const skills = await collectSkillSummaries(pluginDir, plugin)
  await fs.writeFile(path.join(pluginDir, 'AGENTS.md'), `${buildCodexAgentsPointer(plugin, skills, features)}\n`, 'utf-8')
}

